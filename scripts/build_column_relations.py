"""Build app/data/column_relations.json from the relationship catalog of https://xdrinternals.com/relationships/.

Usage:
    python scripts/build_column_relations.py                      # download https://xdrinternals.com/data/column-relations.json
    python scripts/build_column_relations.py column-relations.json   # or a saved copy
    python scripts/build_column_relations.py --check [source]        # only report what changed upstream; exit 1 if anything did

The weekly workflow "Relationship catalog" runs --check, so a change on xdrinternals.com shows up as a failed run.

The catalog (MIT License, Copyright (c) 2025 Fabian & Nathan, https://github.com/MSCloudInternals/XDRInternals) says
which columns join Defender XDR and Sentinel tables: token and session IDs, user, device, app and resource IDs. Kept
per relation: both ends (table, column, JSON path, time column), the kind of key (family), the join guidance, the KQL and
the links to the write-ups it rests on. The longer notes stay on the site.

It also writes web/src/joinColumns.ts: per kind of key, the table columns (and JSON paths) that hold it, for the browser
to tie evidence rows together ("Linked by ID").
"""

from __future__ import annotations

import json
import os
import sys
import urllib.request
from datetime import date
from pathlib import Path

SOURCE = "https://xdrinternals.com/data/column-relations.json"
LICENSE = "MIT License, Copyright (c) 2025 Fabian & Nathan (https://github.com/MSCloudInternals/XDRInternals)"
SIDE = ("table", "column", "path", "timeColumn")


def load(location: str) -> dict:
    if location.startswith("https://"):
        with urllib.request.urlopen(location, timeout=60) as response:
            return json.load(response)
    return json.loads(Path(location).read_text(encoding="utf-8"))


def browser_columns(out: dict) -> str:
    """web/src/joinColumns.ts: per kind of key its label and the [table, column, JSON path] that hold it."""
    ends: dict[str, set[tuple[str, str, str]]] = {}
    for relation in out["relations"]:
        for end in (relation["from"], relation["to"]):
            ends.setdefault(relation["family"], set()).add((end["table"], end["column"], end.get("path", "")))
    columns = {family: {"label": out["families"][family], "ends": sorted(ends[family])} for family in sorted(ends)}
    return (
        "// Generated by scripts/build_column_relations.py from the relationship catalog of https://xdrinternals.com/relationships/\n"
        f"// ({LICENSE}). Do not edit: run the script again.\n"
        "/** Per kind of key: its label and the [table, column, JSON path] that hold it. */\n"
        "export const JOIN_COLUMNS: Record<string, { label: string; ends: [string, string, string][] }> = {\n"
        + "".join(f"  {json.dumps(family)}: {json.dumps(value, ensure_ascii=False)},\n" for family, value in columns.items())
        + "}\n"
    )


TARGET = Path(__file__).resolve().parents[1] / "app" / "data" / "column_relations.json"
SCRIPT = TARGET.parents[2] / "web" / "src" / "joinColumns.ts"


def build(catalog: dict, generated: str) -> dict:
    relations = []
    for item in catalog["relations"]:
        relation = {
            "id": item["id"],
            "title": item["title"],
            "family": item["family"],
            "from": {k: item["from"][k] for k in SIDE if item["from"].get(k)},
            "to": {k: item["to"][k] for k in SIDE if item["to"].get(k)},
            "guidance": item["guidance"],
        }
        if item.get("kql"):
            relation["kql"] = item["kql"]
        sources = sorted({note["sourceUrl"] for note in item.get("otherNotes", []) if note.get("sourceUrl")})
        if sources:
            relation["sources"] = sources
        relations.append(relation)
    return {
        "generated": generated,
        "source": "https://xdrinternals.com/relationships/",
        "license": LICENSE,
        "families": {f["id"]: f["label"] for f in catalog["families"]},
        "relations": sorted(relations, key=lambda r: (r["family"], r["id"])),
    }


def changes(old: dict, new: dict) -> list[str]:
    """What differs between two built catalogs, one line each (the build date aside)."""
    before, after = {r["id"]: r for r in old.get("relations", [])}, {r["id"]: r for r in new["relations"]}
    lines = [
        f"added: {i} ({after[i]['from']['table']}.{after[i]['from']['column']} → {after[i]['to']['table']}.{after[i]['to']['column']})"
        for i in sorted(after.keys() - before.keys())
    ]
    lines += [f"removed: {i}" for i in sorted(before.keys() - after.keys())]
    for i in sorted(before.keys() & after.keys()):
        fields = sorted(k for k in before[i].keys() | after[i].keys() if before[i].get(k) != after[i].get(k))
        if fields:
            lines.append(f"changed: {i} ({', '.join(fields)})")
    if old.get("families") != new["families"]:
        lines.append("changed: the kinds of key (families)")
    return lines


def main(location: str, check: bool = False) -> int:
    old = json.loads(TARGET.read_text(encoding="utf-8")) if TARGET.exists() else {}
    new = build(load(location), old.get("generated", ""))
    found = changes(old, new)
    if check:
        report = (
            f"{len(found)} change(s) in the relationship catalog since {old.get('generated', 'never')}; "
            "run scripts/build_column_relations.py and review the diff:\n" + "\n".join(f"- {line}" for line in found)
            if found
            else f"The relationship catalog is unchanged ({len(new['relations'])} relations)."
        )
        print(report)
        if summary := os.environ.get("GITHUB_STEP_SUMMARY"):
            with open(summary, "a", encoding="utf-8") as handle:
                handle.write(report + "\n")
        return 1 if found else 0
    # The date only moves when the content does, so running the script again changes nothing.
    if found or not new["generated"]:
        new["generated"] = date.today().isoformat()
    TARGET.write_text(json.dumps(new, indent=1, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
    print(
        f"{len(new['relations'])} relations in {len(new['families'])} families → {TARGET}"
        + (f" ({len(found)} changes)" if found else " (unchanged)")
    )
    SCRIPT.write_text(browser_columns(new), encoding="utf-8")
    print(f"key columns for the browser → {SCRIPT}")
    return 0


if __name__ == "__main__":
    arguments = [a for a in sys.argv[1:] if a != "--check"]
    sys.exit(main(arguments[0] if arguments else SOURCE, check="--check" in sys.argv[1:]))
